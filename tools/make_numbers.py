"""Emit LaTeX macros for every number the manuscript cites.

The manuscript must not contain a hand-typed result. Each quantity is read from
the artifact that produced it and written out as a ``\newcommand``; the build
fails if the manuscript references a macro this script did not emit.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

POLICY_MACRO = {
    "local_only": "LocalOnly",
    "edge_only": "EdgeOnly",
    "adaptive_split": "AdaptiveSplit",
    "adaptive_carbon_guard": "CarbonGuard",
    "plm_local_only": "PlmLocalOnly",
    "plm_edge_only": "PlmEdgeOnly",
    "plm_region_constrained_edge": "PlmRegionEdge",
    "plm_adaptive_split": "PlmAdaptiveSplit",
    "plm_adaptive_conformal_guard": "PlmConformalGuard",
}
METRIC_MACRO = {
    "mcc": "Mcc",
    "f1": "FOne",
    "roc_auc": "Auc",
    "average_precision": "Ap",
    "mean_latency_ms": "Latency",
    "mean_total_gco2e": "Carbon",
    "route_rate": "RouteRate",
    "raw_sequence_share_rate": "RawShare",
    "mean_bytes_transferred": "Bytes",
}
COMPARISON_MACRO = {
    "adaptive_split_minus_local_only": "AsVsLo",
    "adaptive_split_minus_edge_only": "AsVsEo",
    "adaptive_carbon_guard_minus_local_only": "CgVsLo",
    "adaptive_carbon_guard_minus_edge_only": "CgVsEo",
    "adaptive_carbon_guard_minus_adaptive_split": "CgVsAs",
    "plm_region_constrained_edge_minus_plm_local_only": "PreVsPlo",
    "plm_region_constrained_edge_minus_plm_edge_only": "PreVsPeo",
    "plm_adaptive_split_minus_plm_local_only": "PasVsPlo",
    "plm_adaptive_split_minus_plm_edge_only": "PasVsPeo",
    "plm_local_only_minus_local_only": "PloVsLo",
    "plm_edge_only_minus_edge_only": "PeoVsEo",
}
NESTED_METRIC = {"roc_auc": "Auc", "average_precision": "Ap", "mcc": "Mcc", "f1": "FOne"}


def fmt(value: Any, places: int = 3) -> str:
    if value is None:
        return r"\textsc{n/a}"
    if isinstance(value, (int,)) and not isinstance(value, bool):
        return str(value)
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value)
    if number != number:  # NaN
        return r"\textsc{n/a}"
    return f"{number:.{places}f}"


def signed(value: Any, places: int = 3) -> str:
    if value is None:
        return r"\textsc{n/a}"
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value)
    return f"{number:+.{places}f}"


class MacroSet:
    def __init__(self) -> None:
        self._macros: dict[str, str] = {}

    def add(self, name: str, value: str) -> None:
        if name in self._macros and self._macros[name] != value:
            raise ValueError(f"macro {name} redefined with a different value")
        self._macros[name] = value

    def render(self, header: str) -> str:
        lines = [f"% {header}", "% Generated by pkg/make_numbers.py -- do not edit by hand.", ""]
        for name in sorted(self._macros):
            lines.append(f"\\newcommand{{\\{name}}}{{{self._macros[name]}}}")
        return "\n".join(lines) + "\n"

    def __len__(self) -> int:
        return len(self._macros)


def add_repeated_eval(m: MacroSet, path: Path) -> None:
    d = json.loads(path.read_text(encoding="utf-8"))
    m.add("NumSeeds", str(len(d["seeds"])))
    m.add("SeedFirst", str(min(d["seeds"])))
    m.add("SeedLast", str(max(d["seeds"])))
    m.add("ValidationFraction", fmt(d["config"]["validation_fraction"], 2))
    m.add("RouteBudgetMax", fmt(d["config"]["route_budget_max"], 2))
    m.add("ThresholdGridSize", str(len(d["config"]["threshold_grid"])))
    for key, label in (("latency", "Latency"), ("energy", "Energy"),
                       ("operational_carbon", "OperationalCarbon"), ("embodied_carbon", "EmbodiedCarbon")):
        m.add(f"Provenance{label}", d["measurement_provenance"][key].replace("_", " "))

    for row in d["aggregate_policy_metrics"]:
        pol = POLICY_MACRO.get(row["policy"])
        if pol is None:
            continue
        for metric, mm in METRIC_MACRO.items():
            for stat, suffix in (("mean", ""), ("ci_low", "Lo"), ("ci_high", "Hi")):
                key = f"{metric}_{stat}"
                if key not in row:
                    continue
                places = 1 if metric == "mean_latency_ms" else 3
                m.add(f"{pol}{mm}{suffix}", fmt(row[key], places))

    for row in d["paired_delta_summary"]:
        cmp_macro = COMPARISON_MACRO.get(row["comparison"])
        if cmp_macro is None:
            continue
        for metric, mm in METRIC_MACRO.items():
            if f"{metric}_mean" not in row:
                continue
            places = 1 if metric == "mean_latency_ms" else 3
            m.add(f"D{cmp_macro}{mm}", signed(row[f"{metric}_mean"], places))
            m.add(f"D{cmp_macro}{mm}Lo", signed(row[f"{metric}_ci_low"], places))
            m.add(f"D{cmp_macro}{mm}Hi", signed(row[f"{metric}_ci_high"], places))

    for row in d["paired_significance"]:
        cmp_macro = COMPARISON_MACRO.get(row["comparison"])
        mm = METRIC_MACRO.get(row["metric"])
        if cmp_macro is None or mm is None:
            continue
        m.add(f"S{cmp_macro}{mm}Wins", str(row["wins"]))
        m.add(f"S{cmp_macro}{mm}Losses", str(row["losses"]))
        m.add(f"S{cmp_macro}{mm}P", fmt(row["p_value_two_sided_sign_test"], 4))


def add_bepipred(m: MacroSet, path: Path) -> None:
    d = json.loads(path.read_text(encoding="utf-8"))
    row = d["baseline_row"]
    for metric, mm in (("roc_auc", "Auc"), ("mcc", "Mcc"), ("f1", "FOne"), ("average_precision", "Ap")):
        m.add(f"Bepipred{mm}", fmt(row[metric]))
    m.add("BepipredThreshold", fmt(d["threshold"], 4))
    m.add("BepipredNumAntigens", str(len(d["per_sequence_rows"])))
    m.add("BepipredResidues", str(sum(int(r["length"]) for r in d["per_sequence_rows"])))
    m.add("BepipredPositives", str(sum(int(r["true_positive_residues"]) for r in d["per_sequence_rows"])))


def add_replication(m: MacroSet, path: Path) -> None:
    """Macros for the test-derived (previously published) selection protocol."""
    d = json.loads(path.read_text(encoding="utf-8"))
    for key, prefix in (("bp3", "TunedBpThree"), ("iedb", "TunedIedb")):
        block = d.get(key)
        if not block:
            continue
        m.add(f"{prefix}Weight", fmt(block["selected"]["weight"], 2))
        m.add(f"{prefix}PositiveCalls", str(block["positive_call_count"]))
        for metric, mm in NESTED_METRIC.items():
            m.add(f"{prefix}Fusion{mm}", fmt(block["selected"][metric]))
            m.add(f"{prefix}Reference{mm}", fmt(block["reference"][metric]))
            m.add(f"{prefix}Delta{mm}", signed(block["delta_vs_reference"][metric], 4))
        comparison = block.get("published_comparison") or {}
        m.add(f"{prefix}ReplicationStatus", str(comparison.get("status", "not run")).replace("_", " "))
        if comparison.get("rows_compared"):
            m.add(f"{prefix}ReplicationRows", str(comparison["rows_compared"]))
            m.add(f"{prefix}ReplicationMaxDiff", f"{comparison['max_absolute_difference']:.1e}")
            m.add(f"{prefix}ReplicationTolerance", f"{comparison['tolerance']:.0e}")


def add_nested_fusion(m: MacroSet, path: Path, prefix: str) -> None:
    d = json.loads(path.read_text(encoding="utf-8"))
    ds = d["dataset"]
    m.add(f"{prefix}Sequences", str(ds["n_sequences"]))
    m.add(f"{prefix}Residues", str(ds["n_residues"]))
    m.add(f"{prefix}Positives", str(ds["n_positive_residues"]))
    w = d["selected_weights"]
    m.add(f"{prefix}WeightMedian", fmt(w["median"], 2))
    m.add(f"{prefix}WeightMin", fmt(w["min"], 2))
    m.add(f"{prefix}WeightMax", fmt(w["max"], 2))
    pooled = d["pooled_out_of_fold"]
    for metric, mm in NESTED_METRIC.items():
        m.add(f"{prefix}Fusion{mm}", fmt(pooled["fusion"][metric], 4))
        m.add(f"{prefix}Reference{mm}", fmt(pooled["reference"][metric], 4))
        m.add(f"{prefix}PooledDelta{mm}", signed(pooled["delta"][metric], 4))
        s = d["paired_statistics"].get(metric, {})
        if s.get("n_folds"):
            m.add(f"{prefix}Delta{mm}", signed(s["mean_delta"], 4))
            m.add(f"{prefix}Delta{mm}Lo", signed(s["ci_low"], 4))
            m.add(f"{prefix}Delta{mm}Hi", signed(s["ci_high"], 4))
            m.add(f"{prefix}Wins{mm}", str(s["wins"]))
            m.add(f"{prefix}Losses{mm}", str(s["losses"]))
            m.add(f"{prefix}P{mm}", fmt(s["p_wilcoxon"], 3))
            m.add(f"{prefix}PSign{mm}", fmt(s["p_sign"], 3))
            if s.get("ties") is not None:
                m.add(f"{prefix}Ties{mm}", str(s["ties"]))
    # Precision of the paired test: the smallest per-antigen difference this
    # design could detect with 80% power at a two-sided 5% level. Reported so a
    # null result can be read against what it was capable of resolving.
    folds = d.get("per_fold", [])
    for metric, mm in NESTED_METRIC.items():
        vals = [r[f"delta_{metric}"] for r in folds if r.get(f"delta_{metric}") is not None]
        if len(vals) > 2:
            n = len(vals)
            mean = sum(vals) / n
            sd = (sum((v - mean) ** 2 for v in vals) / (n - 1)) ** 0.5
            m.add(f"{prefix}Sd{mm}", fmt(sd, 4))
            m.add(f"{prefix}Mde{mm}", fmt(2.8 * sd / (n ** 0.5), 4))


def add_carbon_decomposition(m: MacroSet, path: Path) -> None:
    d = json.loads(path.read_text(encoding="utf-8"))
    m.add("CarbonIdentityError", fmt(d["relative_error"] * 100, 3))
    m.add("CarbonBreakEvenRate", fmt(d["break_even_route_rate"], 3))
    m.add("CarbonBreakEvenPct", fmt(d["break_even_route_rate"] * 100, 1))
    m.add("CarbonPredictedAdaptive", fmt(d["c_adaptive_predicted_gco2e"]))
    op = d.get("operational_term", {})
    for key, name in (("mean_local_gco2e_per_request", "OperationalLocal"),
                      ("mean_edge_gco2e_per_request", "OperationalEdge")):
        if op.get(key) is not None:
            m.add(name, f"{op[key]:.1e}")
    emb = d.get("embodied_term", {})
    for key, name in (("declared_local_gco2e_per_request", "EmbodiedDeclaredLocal"),
                      ("declared_edge_gco2e_per_request", "EmbodiedDeclaredEdge"),
                      ("implied_local_gco2e_per_request", "EmbodiedImpliedLocal"),
                      ("implied_edge_gco2e_per_request", "EmbodiedImpliedEdge")):
        if emb.get(key) is not None:
            m.add(name, fmt(emb[key], 4))


ANTIGEN_METRIC = {"mcc": "Mcc", "roc_auc": "Auc", "average_precision": "Ap", "f1": "FOne",
                  "latency_ms": "Latency", "total_gco2e": "Carbon",
                  "raw_sequence_shared": "RawShare"}


def add_policy_resampling(m: MacroSet, path: Path) -> None:
    """Antigen-level (two-way bootstrap) intervals, prefixed A to distinguish them."""
    d = json.loads(path.read_text(encoding="utf-8"))
    m.add("AntigenBootstrapRepeats", str(d["bootstrap_repeats"]))
    # Multiplicity disclosure: how many intervals the resampling actually
    # produced, against how many the manuscript reports.
    paired = d.get("paired", {})
    if paired:
        quality = [k for k in next(iter(paired.values())) if k in
                   ("mcc", "f1", "roc_auc", "average_precision")]
        m.add("PolicyPairsComputed", str(len(paired)))
        m.add("QualityIntervalsComputed", str(len(paired) * len(quality)))
    m.add("AntigenCount", str(d["n_antigens"]))
    for policy, metrics in d["per_policy"].items():
        pol = POLICY_MACRO.get(policy)
        if pol is None:
            continue
        for metric, mm in ANTIGEN_METRIC.items():
            v = metrics.get(metric)
            if not v:
                continue
            places = 1 if metric == "latency_ms" else 3
            m.add(f"A{pol}{mm}", fmt(v["mean"], places))
            m.add(f"A{pol}{mm}Lo", fmt(v["ci_low"], places))
            m.add(f"A{pol}{mm}Hi", fmt(v["ci_high"], places))
            if v.get("width") is not None:
                m.add(f"A{pol}{mm}Width", fmt(v["width"], places))
    for name, metrics in d["paired"].items():
        cmp_macro = COMPARISON_MACRO.get(name)
        if cmp_macro is None:
            continue
        for metric, mm in ANTIGEN_METRIC.items():
            v = metrics.get(metric)
            if not v:
                continue
            places = 1 if metric == "latency_ms" else 3
            m.add(f"AD{cmp_macro}{mm}", signed(v["mean"], places))
            m.add(f"AD{cmp_macro}{mm}Lo", signed(v["ci_low"], places))
            m.add(f"AD{cmp_macro}{mm}Hi", signed(v["ci_high"], places))


def add_provenance_audit(m: MacroSet, path: Path) -> None:
    """Macros resolving the carbon-constant and dataset-provenance questions."""
    d = json.loads(path.read_text(encoding="utf-8"))
    c = d["carbon_constants"]
    m.add("CarbonLocalFraction", fmt(c["local_fraction_used"], 2))
    m.add("CarbonEdgeFraction", fmt(c["edge_fraction_used"], 2))
    m.add("EmbodiedDeclaredLocal", fmt(c["declared_embodied_local"], 4))
    m.add("EmbodiedDeclaredEdge", fmt(c["declared_embodied_edge"], 4))
    m.add("EmbodiedEffectiveLocal", fmt(c["effective_embodied_local"], 4))
    m.add("EmbodiedEffectiveEdge", fmt(c["effective_embodied_edge"], 4))
    m.add("CarbonReconstructionError", f"{max(c['max_abs_error_local_gco2e'], c['max_abs_error_edge_gco2e']):.0e}")
    m.add("CarbonSequencesChecked", str(c["n_sequences_checked"]))
    flips = [row for row in c["fraction_sensitivity"] if row["break_even_route_rate"] > 0.287]
    m.add("CarbonFractionSettingsTested", str(len(c["fraction_sensitivity"])))
    m.add("CarbonFractionSettingsFlipping", str(len(flips)))
    if flips:
        m.add("CarbonFlipLocalFraction", fmt(flips[0]["local_fraction"], 2))
        m.add("CarbonFlipEdgeFraction", fmt(flips[0]["edge_fraction"], 2))
        m.add("CarbonFlipBreakEven", fmt(flips[0]["break_even_route_rate"], 3))

    i = d["iedb_provenance"]
    m.add("IedbSourceFile", i["source_file"].replace("_", r"\_"))
    m.add("IedbSourceSequences", str(i["source_sequences"]))
    m.add("IedbSubsetTrain", str(i["subset_train"]))
    m.add("IedbSubsetTest", str(i["subset_test"]))
    m.add("IedbLengthMin", str(i["length_bound_min"]))
    m.add("IedbLengthMax", str(i["length_bound_max"]))
    m.add("IedbBpThreeCompared", str(i["bp3_sequences_compared"]))
    m.add("IedbExactOverlap", str(i["exact_sequence_overlap_with_bp3"]))
    m.add("IedbIdOverlap", str(i["id_overlap_with_bp3"]))
    m.add("IedbMaxContainment", fmt(i["max_kmer_containment_vs_bp3"], 3))
    m.add("IedbKmerSize", str(i["kmer_size"]))


def add_transport(m: MacroSet, path: Path, prefix: str) -> None:
    d = json.loads(path.read_text(encoding="utf-8"))
    rows = d.get("summary_rows", [])
    m.add(f"{prefix}SummaryRows", str(len(rows)))
    if rows:
        keys = [k for k in rows[0] if "latency" in k.lower() or "rtt" in k.lower()]
        for row in rows[:1]:
            for k in keys:
                if isinstance(row[k], (int, float)):
                    m.add(f"{prefix}{''.join(p.title() for p in k.split('_'))}", fmt(row[k], 2))
    return


def add_iedb_real(m: MacroSet, path: Path) -> None:
    d = json.loads(path.read_text(encoding="utf-8"))
    et = d["external_test"]
    m.add("IedbNumPolicies", str(len(et)))
    for policy, block in et.items():
        pol = POLICY_MACRO.get(policy)
        if pol is None:
            continue
        s = block.get("summary", {})
        for metric, mm in (("roc_auc", "Auc"), ("mcc", "Mcc"), ("f1", "FOne"), ("average_precision", "Ap")):
            if metric in s and s[metric] is not None:
                m.add(f"Iedb{pol}{mm}", fmt(s[metric]))
    for note in d.get("limitations", [])[:1]:
        pass


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--repeated-eval", required=True)
    p.add_argument("--bepipred-summary", required=True)
    p.add_argument("--replication", required=True)
    p.add_argument("--nested-bp3", required=True)
    p.add_argument("--nested-iedb", required=True)
    p.add_argument("--provenance-audit")
    p.add_argument("--policy-resampling")
    p.add_argument("--carbon-decomposition")
    p.add_argument("--transport")
    p.add_argument("--two-node-transport")
    p.add_argument("--iedb-real-results")
    p.add_argument("--output", required=True)
    a = p.parse_args()

    m = MacroSet()
    add_repeated_eval(m, Path(a.repeated_eval))
    add_bepipred(m, Path(a.bepipred_summary))
    add_replication(m, Path(a.replication))
    add_nested_fusion(m, Path(a.nested_bp3), "NestedBpThree")
    add_nested_fusion(m, Path(a.nested_iedb), "NestedIedb")
    if a.provenance_audit:
        add_provenance_audit(m, Path(a.provenance_audit))
    if a.policy_resampling:
        add_policy_resampling(m, Path(a.policy_resampling))
    if a.carbon_decomposition:
        add_carbon_decomposition(m, Path(a.carbon_decomposition))
    if a.transport:
        add_transport(m, Path(a.transport), "Transport")
    if a.two_node_transport:
        add_transport(m, Path(a.two_node_transport), "TwoNode")
    if a.iedb_real_results:
        add_iedb_real(m, Path(a.iedb_real_results))

    out = Path(a.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(m.render("EdgeConBCE generated manuscript numbers"), encoding="utf-8")
    print(f"wrote {len(m)} macros to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
